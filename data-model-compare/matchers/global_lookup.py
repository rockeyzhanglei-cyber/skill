# -*- coding: utf-8 -*-
"""
全局查找：字段基名 / 语义基名归一化（P1-2 第三刀，拆分自 standard_comparator.py）

用于"跨表全局查找"通道：把字段名归一化成基名（norm_base）或语义基名
（semantic_base），再在全局范围内找候选源字段。

拆分依据（AST 分析，三种引用形式全查）：
- 4 个函数全部不读写实例状态（原均为 classmethod）
- 引用的 8 个常量已一并下沉，类内无其他使用点
- 组内互不调用

原类 StandardComparator 保留同名薄委托（classmethod 语义不变），
调用方 `self._xxx(...)` / `cls._xxx(...)` 均无需改动。

⚠️ 维护约定：保持无状态。
"""


import re


# ============================================================================
# 常量（P1-2 从 StandardComparator 下沉至此，单一事实来源）
# 原类以 `_XXX = <mod>.XXX` 别名引用，故 XXX / self._XXX 既有用法不变。
# ============================================================================

# ===== 跨表同义级兜底（P4）=====
# 只做"同义变体"归一，不剥离括号说明——括号里的内容（如"对应其他诊断13"）
# 恰恰是区分主子表展开字段的关键，剥离会造成大面积误配。
GLOBAL_NORM_PAIRS = [
    ('（', '('), ('）', ')'),          # 全角括号归一
    ('医师', '医生'), ('大夫', '医生'),
    ('编码', '代码'), ('代号', '代码'),
    ('唯一标识', '标识'),
    ('名字', '名称'), ('姓名', '名称'),
]

# 结尾的"种类词"——比较时剥离，改由 _field_kind_compatible 单独把关，
# 这样 "麻醉分级代码" 才能匹配到源标准里没有后缀的 "麻醉分级"。
GLOBAL_TAIL_KINDS = ['唯一标识', '流水号', '名称', '代码', '编码', '代号',
                      '标识', '标志', '序号', '编号', '签名']

# 纯噪音字符：分隔符、标点、结构助词。两个标准对同一数据元的写法差异
# 大量集中在这里，不去掉会造成大面积漏配：
#   收退费日期时间      == 收/退费日期时间
#   损伤、中毒的外部原因 == 损伤中毒外部原因
GLOBAL_NOISE_CHARS = '、，,；;／/·　 的'

# 全局语义兜底用的"前缀"——比较时剥离，使组件字段匹配其基名：
#   患者电子邮件地址 -> 电子邮件地址（匹配源"电子邮件地址"）
#   住院主要诊断 -> 主要诊断（匹配源"主要诊断"）
# 仅在 _global_semantic_lookup 中使用，不影响精确/同义主链路。
# 注意：
#  - 就诊/急诊 不在剥离列表：剥离后只剩"流水号/费用总金额"等通用词，
#    会把 就诊流水号 错配到 住院流水号（角色闸门不覆盖 就诊vs住院）。
#  - 出生地/户籍地/居住地/常住地/工作地 等"地址位置前缀"受保护（见
#    _ADDR_PROTECTED_PREFIXES），不剥离——它们是地址组件族（省市/地市/
#    区县/街道/村路弄/门牌/邮编）的**消歧关键**：出生地-省市代码 只能
#    匹配 出生地（省市），不能匹配 户籍地址（省市）。
GLOBAL_LEAD_PREFIXES = ['患者', '本人', '住院', '门诊', '入院', '出院',
                         '产前', '产后', '主诉', '既往', '关键']

# 地址组件同义词（先括号归一、再整词替换）。两个标准对同一地址组件的
# 写法差异集中在这里：
#   省（自治区、直辖市） == 省市    市(地区、州) == 地市
#   县(区) == 区县                  乡(镇、街道办事处)/乡镇、街道 == 街道乡镇
#   村(街、路、弄等)/村、街、路、弄 == 村街路弄
#   门牌号码 == 门牌                邮政编码/邮编 == 邮政代码
# 顺序敏感：长词在前（省（自治区、直辖市） 先于 省市 无关，但 门牌号码
# 先于 门牌；邮编 与 邮政编码 互不包含，任意顺序）。
ADDR_COMPONENT_PAIRS = [
    ('省（自治区、直辖市）', '省市'),
    ('省(自治区、直辖市)', '省市'),
    ('市(地区、州)', '地市'),
    ('市（地区、州）', '地市'),
    ('乡(镇、街道办事处)', '街道乡镇'),
    ('乡（镇、街道办事处）', '街道乡镇'),
    ('乡镇、街道', '街道乡镇'),
    ('村、街、路、弄', '村街路弄'),
    ('村(街、路、弄等)', '村街路弄'),
    ('村（街、路、弄等）', '村街路弄'),
    ('门牌号码', '门牌'),
    ('邮政编码', '邮政代码'),
    ('邮编', '邮政代码'),
]

# 地址位置同义词（先长后短）：源标准的写法 -> 目标省平台的写法。
#   现住址/现住 == 居住地     户籍地址 == 户籍地
#   单位地址/工作单位及地址 == 单位    联系人地址 == 联系人
ADDR_LOC_PAIRS = [
    ('工作单位及地址', '单位'),
    ('联系人地址', '联系人'),
    ('户籍地址', '户籍地'),
    ('单位地址', '单位'),
    ('家庭地址', '家庭'),
    ('现住址', '居住地'),
    ('现住', '居住地'),
]

# ===== 陈旧正向映射治理（P5）=====
EN_NORM_PAIRS = [('doctor', 'dr'), ('department', 'dept'), ('number', 'no'),
                  ('code', 'no'), ('identity', 'id'), ('identifier', 'id')]

# P5 局部同义归一：只用于"知识库映射体检"，不影响主匹配链路。
# 覆盖实测中导致误报的同义写法差异。
# 顺序敏感：长词在前（身份证件 -> 证件，避免 身份证 先命中留下"证件件"）
P5_NORM_PAIRS = [('病人', '患者'), ('号码', '号'),
                  ('职工', '人员'), ('员工', '人员'), ('工号', '人员代码'),
                  ('身份证件', '证件'), ('身份证', '证件'),
                  ('药物', '药品'), ('药械', '药品')]



def norm_base(cn: str) -> str:
    """归一化并剥离尾部种类词，得到跨表比对用的基名。"""
    s = cn or ''
    for a, b in GLOBAL_NORM_PAIRS:
        s = s.replace(a, b)
    for ch in GLOBAL_NOISE_CHARS:
        s = s.replace(ch, '')
    for k in sorted(GLOBAL_TAIL_KINDS, key=len, reverse=True):
        if s.endswith(k) and len(s) > len(k):
            s = s[:-len(k)]
            break
    return s.strip()
def semantic_base(cn: str) -> str:
    """归一化并剥离前缀，得到全局语义兜底用的基名。

    与 _global_norm_base 的差异（针对实测 3429 新增字段的三大漏配源）：
    1. 地址组件/位置同义词归一：出生地-省市代码 == 出生地（省市）、
       户籍地-门牌号码 == 户籍地址（门牌号码）、居住地-详细地址 == 现住详细地址。
    2. 尾部种类词"有条件剥离"：剩余基名 >= 4 字才剥。避免 就诊流水号 ->
       就诊（源 26 个候选、歧义）、患者姓名 -> 患者（源 118 个候选）这类
       过度剥离把唯一性闸门直接废掉。
    3. 前缀"有条件剥离"：剩余基名 >= 4 字才剥，且地址位置前缀（出生地/
       户籍地/居住地/常住地…）受保护不剥——它们是地址组件族的消歧关键。
    """
    s = cn or ''
    # 1. 基础同义归一 + 全角括号归一
    for a, b in GLOBAL_NORM_PAIRS:
        s = s.replace(a, b)
    # 2. 地址组件同义词（长词在前）
    for a, b in ADDR_COMPONENT_PAIRS:
        s = s.replace(a, b)
    # 3. 地址位置同义词（长词在前）
    for a, b in ADDR_LOC_PAIRS:
        s = s.replace(a, b)
    # 4. 去噪（含括号与连字符：出生地-省市代码 -> 出生地省市代码）
    for ch in GLOBAL_NOISE_CHARS + '()（）-－—':
        s = s.replace(ch, '')
    # 5. 尾部种类词：仅当剩余基名 >= 4 才剥离
    for k in sorted(GLOBAL_TAIL_KINDS, key=len, reverse=True):
        if s.endswith(k) and len(s) - len(k) >= 4:
            s = s[:-len(k)]
            break
    # 6. 前缀剥离：仅当剩余基名 >= 4；地址位置前缀受保护
    changed = True
    while changed:
        changed = False
        s2 = re.sub(r'^[\-—、·\s]+', '', s)
        for p in GLOBAL_LEAD_PREFIXES:
            if s2.startswith(p) and len(s2) - len(p) >= 4:
                s2 = s2[len(p):]
                s2 = re.sub(r'^[\-—、·\s]+', '', s2)
                changed = True
                break
        s = s2
    return s.strip()
def en_core(n: str) -> str:
    s = (n or '').lower().replace('_', '')
    for a, b in EN_NORM_PAIRS:
        s = s.replace(a, b)
    return s
def p5_norm(cn: str) -> str:
    """体检用同义归一（全局归一对 + P5 局部补充）。"""
    s = cn or ''
    for a, b in GLOBAL_NORM_PAIRS:
        s = s.replace(a, b)
    for a, b in P5_NORM_PAIRS:
        s = s.replace(a, b)
    return s