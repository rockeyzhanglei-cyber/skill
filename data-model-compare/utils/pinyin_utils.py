def chinese_to_pinyin_initials(chinese_text):
    """将中文文本转换为拼音首字母缩写

    Args:
        chinese_text: 中文字符串

    Returns:
        拼音首字母缩写（小写）
    """
    if not chinese_text:
        return ''

    result = []
    for char in chinese_text:
        # 如果是英文字母或数字，直接保留
        if char.isascii() and char.isalnum():
            result.append(char.lower())
        # 如果是中文字符，查找拼音首字母
        elif char in PINYIN_INITIALS:
            result.append(PINYIN_INITIALS[char].lower())
        # 其他字符（标点等）跳过
        else:
            continue

    return ''.join(result)

def generate_english_field_name(chinese_name, standard_version='5.0'):
    """生成英文字段名

    Args:
        chinese_name: 中文名称
        standard_version: 标准版本（'5.0'/'5.X' 或 '6.0'）

    Returns:
        英文字段名（大写）
        - 5.X版本：拼音首字母缩写（如"健康档案编号" -> "JKABH"）
        - 6.0版本：拼音全拼或英文（如"健康档案编号" -> "JIANKANGDANGANBIANHAO"）
    """
    if not chinese_name:
        return ''

    # 判断版本
    if standard_version in ['6.0', 'v6', '6']:
        # 6.0版本：使用拼音全拼
        return _chinese_to_pinyin_full(chinese_name).upper()
    else:
        # 5.X版本：使用拼音首字母缩写
        return chinese_to_pinyin_initials(chinese_name).upper()


